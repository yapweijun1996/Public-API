const tables: Record<UiLocale, MessageTable> = { en, 'zh-CN': zhCN }

export function readUiLocale(): UiLocale {
  try {
    const stored = window.localStorage.getItem(UI_LOCALE_STORAGE_KEY)
    if (stored === 'zh-CN' || stored === 'en') return stored
  } catch {
    // Storage can be blocked; English remains the stable default.
  }
  return 'en'
}

export function uiText(locale: UiLocale, key: UiMessageKey, values: Record<string, string | number> = {}): string {
  return Object.entries(values).reduce(
    (message, [name, value]) => message.replaceAll(`{${name}}`, String(value)),
    tables[locale][key],
  )
}
